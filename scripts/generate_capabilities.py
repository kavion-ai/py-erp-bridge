"""Generate docs/capabilities.md from the adapters, so that it cannot drift."""

from __future__ import annotations

from pathlib import Path

from py_erp_bridge import Operation, available_providers, registry
from py_erp_bridge.client import CANONICAL_MODELS

TARGET = Path(__file__).parent.parent / "docs" / "capabilities.md"
LETTERS = {
    Operation.LIST: "L",
    Operation.GET: "G",
    Operation.CREATE: "C",
    Operation.UPDATE: "U",
    Operation.DELETE: "D",
}


def yes(value: bool) -> str:
    """Render a flag."""
    return "yes" if value else "no"


def render() -> str:
    """Return the document."""
    infos = [registry.get(n) for n in available_providers() if n != "example_erp"]
    out = [
        "# Capabilities",
        "",
        "Generated by `scripts/generate_capabilities.py`; do not edit.",
        "",
        "No provider has been run against a live system. *Evidence* says how well the wire",
        "details are backed: `official_docs` (read in vendor documentation for this release),",
        "`secondary` (third-party material only) or `unconfirmed` (established convention that",
        "could not be checked). Confirm the latter two in your system's metadata.",
        "",
        "## Features",
        "",
        "| Provider | Protocols | Auth types | Sort | Native bulk | Webhook registration | Files |",
        "|---|---|---|---|---|---|---|",
    ]
    for cls in infos:
        i = cls.info
        out.append(
            f"| `{i.name}` | {', '.join(sorted(i.protocols))} | {', '.join(sorted(i.auth_types))}"
            f" | {yes(i.sorting)} | {yes(i.native_bulk)} | {yes(i.webhook_registration)}"
            f" | {yes(i.file_upload)} |"
        )
    out += [
        "",
        "## Operations",
        "",
        "L list, G get, C create, U update, D delete.",
        "",
        "| Entity | " + " | ".join(f"`{c.info.name}`" for c in infos) + " |",
        "|---" * (len(infos) + 1) + "|",
    ]
    for entity in CANONICAL_MODELS:
        cells = []
        for cls in infos:
            spec = cls.default_entities.get(entity)
            ops = spec.operations if spec else frozenset()
            cells.append("".join(v for k, v in LETTERS.items() if k in ops) or "-")
        out.append(f"| {entity} | " + " | ".join(cells) + " |")
    for cls in infos:
        out += ["", f"## {cls.info.title} (`{cls.info.name}`)", ""]
        operations = ", ".join(f"`{o}`" for o in cls.operations())
        out += [f"Provider operations for `execute()`: {operations}.", ""]
        out += [f"- {text}" for text in cls.info.limitations]
        out += [
            "",
            "| Entity | Provider object | Key | Mapped fields | Evidence | Notes |",
            "|---|---|---|---|---|---|",
        ]
        for name, spec in cls.default_entities.items():
            fields = ", ".join(
                f.canonical + ("" if f.writable and Operation.UPDATE in spec.operations else "*")
                for f in spec.fields
                if f.canonical != "id"
            )
            lines = " + items" if spec.lines else ""
            key = ", ".join(spec.key_fields)
            out.append(
                f"| {name} | `{spec.path}` | `{key}` | {fields}{lines} | {spec.evidence.value}"
                f" | {spec.notes} |"
            )
        out += ["", "`*` read-only or not updatable.", "", "Official documentation:", ""]
        out += [f"- <{url}>" for url in cls.info.documentation]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
